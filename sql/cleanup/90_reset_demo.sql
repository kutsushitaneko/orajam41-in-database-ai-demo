-- Destructive: back up the named demo assets before execution.
-- ORAJAM41USER on arakawalab only. Never drop the DB user or system-managed tables.
-- Change l_confirm only after reviewing scope. l_drop_model controls ONNX deletion.
DECLARE
  l_confirm VARCHAR2(80) := 'NOT_CONFIRMED';
  l_drop_model BOOLEAN := FALSE;
  n PLS_INTEGER;
  db_name VARCHAR2(128) := LOWER(SYS_CONTEXT('USERENV','DB_NAME'));
BEGIN
  IF l_confirm <> 'RESET_ORAJAM41_DEMO'
     OR SYS_CONTEXT('USERENV','SESSION_USER') <> 'ORAJAM41USER'
     OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'ORAJAM41USER'
     OR NOT (db_name='arakawalab' OR db_name LIKE '%\_arakawalab' ESCAPE '\') THEN
    RAISE_APPLICATION_ERROR(-20041, 'Explicit confirmation and expected database/schema required');
  END IF;
  DBMS_CLOUD_AI_AGENT.CLEAR_TEAM;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TEAMS WHERE AGENT_TEAM_NAME='OJ41_SUPPORT_TEAM';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TEAM(team_name=>'OJ41_SUPPORT_TEAM'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TEAMS WHERE AGENT_TEAM_NAME='ORAJAM41_SMOKE_TEAM';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TEAM(team_name=>'ORAJAM41_SMOKE_TEAM'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TASKS WHERE TASK_NAME='OJ41_SUPPORT_TASK';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TASK(task_name=>'OJ41_SUPPORT_TASK'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TASKS WHERE TASK_NAME='ORAJAM41_SMOKE_TASK';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TASK(task_name=>'ORAJAM41_SMOKE_TASK'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENTS WHERE AGENT_NAME='OJ41_SUPPORT_AGENT';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_AGENT(agent_name=>'OJ41_SUPPORT_AGENT'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENTS WHERE AGENT_NAME='ORAJAM41_SMOKE_AGENT';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_AGENT(agent_name=>'ORAJAM41_SMOKE_AGENT'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TOOLS WHERE TOOL_NAME='OJ41_LOOKUP_CONTRACT';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TOOL(tool_name=>'OJ41_LOOKUP_CONTRACT'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TOOLS WHERE TOOL_NAME='OJ41_SEARCH_KNOWLEDGE';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TOOL(tool_name=>'OJ41_SEARCH_KNOWLEDGE'); END IF;
  SELECT COUNT(*) INTO n FROM USER_AI_AGENT_TOOLS WHERE TOOL_NAME='ORAJAM41_SMOKE_TOOL';
  IF n > 0 THEN DBMS_CLOUD_AI_AGENT.DROP_TOOL(tool_name=>'ORAJAM41_SMOKE_TOOL'); END IF;
  SELECT COUNT(*) INTO n FROM USER_CLOUD_AI_PROFILES WHERE PROFILE_NAME='OJ41_BUSINESS_AI';
  IF n > 0 THEN DBMS_CLOUD_AI.DROP_PROFILE(profile_name=>'OJ41_BUSINESS_AI'); END IF;
  SELECT COUNT(*) INTO n FROM USER_CLOUD_AI_PROFILES WHERE PROFILE_NAME='ORAJAM41_GENAI_SMOKE';
  IF n > 0 THEN DBMS_CLOUD_AI.DROP_PROFILE(profile_name=>'ORAJAM41_GENAI_SMOKE'); END IF;
  SELECT COUNT(*) INTO n FROM USER_CLOUD_AI_PROFILES WHERE PROFILE_NAME='OJ41_NL2SQL_BASELINE';
  IF n > 0 THEN DBMS_CLOUD_AI.DROP_PROFILE(profile_name=>'OJ41_NL2SQL_BASELINE'); END IF;
  SELECT COUNT(*) INTO n FROM USER_CLOUD_AI_PROFILES WHERE PROFILE_NAME='OJ41_NL2SQL_TUNED';
  IF n > 0 THEN DBMS_CLOUD_AI.DROP_PROFILE(profile_name=>'OJ41_NL2SQL_TUNED'); END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='VIEW' AND object_name='OJ41_VISIBLE_CHUNKS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP VIEW OJ41_VISIBLE_CHUNKS'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='VIEW' AND object_name='OJ41_VISIBLE_CONTRACTS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP VIEW OJ41_VISIBLE_CONTRACTS'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='VIEW' AND object_name='OJ41_VISIBLE_DEVICES';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP VIEW OJ41_VISIBLE_DEVICES'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='VIEW' AND object_name='OJ41_VISIBLE_KNOWLEDGE';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP VIEW OJ41_VISIBLE_KNOWLEDGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='VIEW' AND object_name='ORAJAM41_ENV_PROBE';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP VIEW ORAJAM41_ENV_PROBE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='FUNCTION' AND object_name='OJ41_CONTRACT_TOOL';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP FUNCTION OJ41_CONTRACT_TOOL'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='FUNCTION' AND object_name='OJ41_KNOWLEDGE_TOOL';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP FUNCTION OJ41_KNOWLEDGE_TOOL'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='FUNCTION' AND object_name='ORAJAM41_PROBE_STATUS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP FUNCTION ORAJAM41_PROBE_STATUS'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='PACKAGE' AND object_name='OJ41_AGENT_CTX';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP PACKAGE OJ41_AGENT_CTX'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='PACKAGE' AND object_name='OJ41_CASE_CTX';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP PACKAGE OJ41_CASE_CTX'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_BULK_STAGE';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_BULK_STAGE PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_BULK_DOCS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_BULK_DOCS PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_BULK_PARTS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_BULK_PARTS PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_CHUNKS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_CHUNKS PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_CONTRACTS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_CONTRACTS PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_DEVICES';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_DEVICES PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_KNOWLEDGE';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_KNOWLEDGE PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_SUPPORT_CASES';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_SUPPORT_CASES PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_CUSTOMERS';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_CUSTOMERS PURGE'; END IF;
  SELECT COUNT(*) INTO n FROM user_objects WHERE object_type='TABLE' AND object_name='OJ41_RUN';
  IF n > 0 THEN EXECUTE IMMEDIATE 'DROP TABLE OJ41_RUN PURGE'; END IF;
  IF l_drop_model THEN
    SELECT COUNT(*) INTO n FROM user_mining_models WHERE model_name='MULTILINGUAL_E5_LARGE';
    IF n > 0 THEN DBMS_VECTOR.DROP_ONNX_MODEL(model_name=>'MULTILINGUAL_E5_LARGE'); END IF;
  END IF;
END;
